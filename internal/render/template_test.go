// TestTemplateCLIMinimalShellGoldens locks golden renders for each catalog
// template fixture used by the CLI minimal shell (README + cmd main).
func TestTemplateCLIMinimalShellGoldens(t *testing.T) {
	log := testutil.New(t)
	log.Phase("arrange")
	cat := mustLoadCatalog(t)
	data := minimalCLITemplateData()
	jobs := []render.TemplateJob{
		{
			Path:   "README.md",
			Mode:   "0644",
			Source: "core/files/README.md.tmpl",
			Owner:  "core",
			Data:   data,
		},
		{
			Path:   "cmd/minimal-cli/main.go",
			Mode:   "0644",
			Source: "archetypes/cli/files/main.go.tmpl",
			Owner:  "archetype:cli",
			Data:   data,
		},
	}
	log.Inputs(map[string]string{
		"mechanism": "template",
		"files":     fmt.Sprintf("%d", len(jobs)),
		"name":      data.Name,
		"binary":    data.Binary,
	})
	log.Fixture("fixture", "minimal-cli")
	log.PhaseEnd("arrange", testutil.OutcomeOK)

	log.Phase("act")
	buf := render.NewMemoryWriter()
	inv, err := render.RenderTemplateAll(cat, jobs, buf)
	if err != nil {
		log.Fail("render_template_all", err.Error())
	}
	log.Step("inventory", testutil.OutcomeOK, fmt.Sprintf("n=%d paths=%v", inv.Len(), inv.Paths()))
	log.PhaseEnd("act", testutil.OutcomeOK)

	log.Phase("assert")
	log.Assert("entry_count", inv.Len() == 2, 2, inv.Len())

	// Sorted by path: README.md, cmd/minimal-cli/main.go
	cases := []struct {
		path   string
		source string
		golden string
		owner  string
		isGo   bool
	}{
		{
			path:   "README.md",
			source: "core/files/README.md.tmpl",
			golden: "minimal_cli_readme",
			owner:  "core",
		},
		{
			path:   "cmd/minimal-cli/main.go",
			source: "archetypes/cli/files/main.go.tmpl",
			golden: "minimal_cli_main_go",
			owner:  "archetype:cli",
			isGo:   true,
		},
	}
	for _, tc := range cases {
		e, ok := inv.EntryByPath(tc.path)
		log.Assert("found_"+tc.path, ok, true, ok)
		log.Assert("mech_"+tc.path, e.Mechanism == render.MechanismTemplate,
			render.MechanismTemplate, e.Mechanism)
		log.Assert("mode_"+tc.path, e.Mode == "0644", "0644", e.Mode)
		log.Assert("source_"+tc.path, e.Source == tc.source, tc.source, e.Source)
		log.Assert("owner_"+tc.path, e.Owner == tc.owner, tc.owner, e.Owner)

		src, rerr := cat.Read(tc.source)
		if rerr != nil {
			log.Fail("read_source_"+tc.path, rerr.Error())
		}
		srcDig := digestOf(src)
		log.Assert("source_digest_"+tc.path, e.SourceDigest == srcDig, srcDig, e.SourceDigest)

		out, cok := inv.Content(tc.path)
		log.Assert("content_present_"+tc.path, cok, true, cok)
		log.Assert("content_digest_"+tc.path, e.ContentDigest == digestOf(out),
			digestOf(out), e.ContentDigest)
		// Template output differs from source when substitution occurs.
		log.Assert("digest_differs_"+tc.path, e.SourceDigest != e.ContentDigest,
			true, e.SourceDigest != e.ContentDigest)

		// No CR in rendered output (LF-only).
		log.Assert("lf_only_"+tc.path, !bytes.Contains(out, []byte{'\r'}),
			true, !bytes.Contains(out, []byte{'\r'}))

		if tc.isGo {
			log.Assert("go_package_"+tc.path, bytes.Contains(out, []byte("package main")),
				true, bytes.Contains(out, []byte("package main")))
			log.Assert("go_binary_"+tc.path, bytes.Contains(out, []byte(data.Binary)),
				true, bytes.Contains(out, []byte(data.Binary)))
		} else {
			log.Assert("name_in_readme", bytes.Contains(out, []byte("# "+data.Name)),
				true, bytes.Contains(out, []byte("# "+data.Name)))
			log.Assert("desc_in_readme", bytes.Contains(out, []byte(data.Description)),
				true, bytes.Contains(out, []byte(data.Description)))
		}

		golden := testutil.GoldenPath(filepath.Join(packageDir(t), "testdata"), tc.golden)
		testutil.CompareGolden(t, golden, out)
		log.Step("file", testutil.OutcomeOK, fmt.Sprintf(
			"template_id=%s input_digest=%s output_digest=%s path=%s outcome=ok",
			e.Source, e.SourceDigest, e.ContentDigest, e.Path,
		))
		log.NotePath(e.Path)
		log.NoteID(string(e.ContentDigest))
	}
	log.PhaseEnd("assert", testutil.OutcomeOK)
}

