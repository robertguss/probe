// TestTemplateNoNestedPartials rejects define + template include.
func TestTemplateNoNestedPartials(t *testing.T) {
	log := testutil.New(t)
	log.Phase("no_partials")
	cat := templateFixtureCatalog()

	cases := []struct {
		name   string
		source string
		sub    string
	}{
		{name: "nested_define", source: "fixtures/nested_define.tmpl", sub: "define"},
		{name: "include", source: "fixtures/include_only.tmpl", sub: "include"},
	}
	for _, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			sub := testutil.New(t)
			sub.Phase("reject")
			sub.Inputs(map[string]string{"source": tc.source, "case": tc.name})
			inv, err := render.RenderTemplate(cat, render.TemplateJob{
				Path:   "out.txt",
				Mode:   "0644",
				Source: tc.source,
				Data:   minimalCLITemplateData(),
			}, nil)
			sub.Assert("nil_inventory", inv == nil, true, inv == nil)
			if err == nil {
				sub.Fail("expected_error", "want render.failed for "+tc.name)
			}
			fe := asFoundry(t, err)
			sub.Assert("id", fe.ID() == diagnostic.IDRenderFailed,
				diagnostic.IDRenderFailed, fe.ID())
			msg := fe.Error()
			sub.Assert("mentions_restriction",
				strings.Contains(msg, "not allowed") ||
					strings.Contains(msg, "complete-file") ||
					strings.Contains(msg, "partial") ||
					strings.Contains(msg, "include") ||
					strings.Contains(msg, "definition"),
				true, msg)
			sub.Step("reject", testutil.OutcomeOK, fmt.Sprintf(
				"template_id=%s error_id=%s outcome=refused",
				tc.source, fe.ID(),
			))
			sub.PhaseEnd("reject", testutil.OutcomeOK)
		})
	}
	log.PhaseEnd("no_partials", testutil.OutcomeOK)
}

// TestTemplateNoExternalExecution rejects exec/call-style actions and proves
// ordinary renders never shell out (pure buffer only).
func TestTemplateNoExternalExecution(t *testing.T) {
	log := testutil.New(t)
	log.Phase("no_exec")
	cat := templateFixtureCatalog()

	// Hostile function names fail closed.
	for _, src := range []string{
		"fixtures/forbidden_call.tmpl",
		"fixtures/forbidden_exec.tmpl",
	} {
		src := src
		t.Run(src, func(t *testing.T) {
			t.Parallel()
			sub := testutil.New(t)
			sub.Phase("reject")
			inv, err := render.RenderTemplate(cat, render.TemplateJob{
				Path:   "out.txt",
				Mode:   "0644",
				Source: src,
				Data:   minimalCLITemplateData(),
			}, nil)
			sub.Assert("nil_inventory", inv == nil, true, inv == nil)
			if err == nil {
				sub.Fail("expected_error", "want render.failed for hostile func")
			}
			fe := asFoundry(t, err)
			sub.Assert("id", fe.ID() == diagnostic.IDRenderFailed,
				diagnostic.IDRenderFailed, fe.ID())
			sub.Step("reject", testutil.OutcomeOK, fmt.Sprintf(
				"template_id=%s error_id=%s outcome=refused",
				src, fe.ID(),
			))
			sub.PhaseEnd("reject", testutil.OutcomeOK)
		})
	}

	// Safe render produces only substituted text — no side-effect channels.
	inv, err := render.RenderTemplate(cat, render.TemplateJob{
		Path:   "hello.txt",
		Mode:   "0644",
		Source: "fixtures/simple.tmpl",
		Data:   minimalCLITemplateData(),
	}, nil)
	if err != nil {
		log.Fail("safe_render", err.Error())
	}
	out, ok := inv.Content("hello.txt")
	log.Assert("present", ok, true, ok)
	want := "Hello minimal-cli (minimal-cli)\n"
	log.Assert("bytes", string(out) == want, want, string(out))
	log.Step("safe", testutil.OutcomeOK, fmt.Sprintf(
		"template_id=fixtures/simple.tmpl input_digest=%s output_digest=%s outcome=ok",
		inv.Entries()[0].SourceDigest, inv.Entries()[0].ContentDigest,
	))
	log.PhaseEnd("no_exec", testutil.OutcomeOK)
}

