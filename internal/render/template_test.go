// TestTemplateDeterminism ensures identical inputs produce equal inventories
// under repeated invocation (pair with go test -count=2).
func TestTemplateDeterminism(t *testing.T) {
	log := testutil.New(t)
	log.Phase("determinism")
	cat := mustLoadCatalog(t)
	data := minimalCLITemplateData()
	jobs := []render.TemplateJob{
		{Path: "README.md", Mode: "0644", Source: "core/files/README.md.tmpl", Owner: "core", Data: data},
		{Path: "cmd/minimal-cli/main.go", Mode: "0644", Source: "archetypes/cli/files/main.go.tmpl", Owner: "archetype:cli", Data: data},
	}

	a, err := render.RenderTemplateAll(cat, jobs, render.NewMemoryWriter())
	if err != nil {
		log.Fail("render_a", err.Error())
	}
	b, err := render.RenderTemplateAll(cat, jobs, render.NewMemoryWriter())
	if err != nil {
		log.Fail("render_b", err.Error())
	}
	log.Assert("equal", a.Equal(b), true, a.Equal(b))
	for i, e := range a.Entries() {
		log.Assert("path_"+e.Path, e.Path == b.Entries()[i].Path, e.Path, b.Entries()[i].Path)
		log.Assert("digest_"+e.Path, e.ContentDigest == b.Entries()[i].ContentDigest,
			e.ContentDigest, b.Entries()[i].ContentDigest)
		log.Step("file", testutil.OutcomeOK, fmt.Sprintf(
			"template_id=%s input_digest=%s output_digest=%s outcome=ok",
			e.Source, e.SourceDigest, e.ContentDigest,
		))
	}
	log.PhaseEnd("determinism", testutil.OutcomeOK)
}

