// TestTemplateEmbeddedTUIMain renders the real catalog TUI main stub.
func TestTemplateEmbeddedTUIMain(t *testing.T) {
	log := testutil.New(t)
	log.Phase("embedded_tui")
	cat := mustLoadCatalog(t)
	data := render.TemplateData{
		Name:        "minimal-tui",
		Binary:      "minimal-tui",
		Module:      "github.com/example/minimal-tui",
		Description: "Minimal TUI",
		Archetype:   "tui",
		Visibility:  "private",
	}
	src := "archetypes/tui/files/main.go.tmpl"
	inv, err := render.RenderTemplate(cat, render.TemplateJob{
		Path:   "cmd/minimal-tui/main.go",
		Mode:   "0644",
		Source: src,
		Owner:  "archetype:tui",
		Data:   data,
	}, nil)
	if err != nil {
		log.Fail("render", err.Error())
	}
	out, ok := inv.Content("cmd/minimal-tui/main.go")
	log.Assert("present", ok, true, ok)
	log.Assert("binary", bytes.Contains(out, []byte("minimal-tui")),
		true, bytes.Contains(out, []byte("minimal-tui")))
	log.Assert("package", bytes.Contains(out, []byte("package main")),
		true, bytes.Contains(out, []byte("package main")))
	e := inv.Entries()[0]
	log.Step("file", testutil.OutcomeOK, fmt.Sprintf(
		"template_id=%s input_digest=%s output_digest=%s outcome=ok",
		e.Source, e.SourceDigest, e.ContentDigest,
	))
	log.PhaseEnd("embedded_tui", testutil.OutcomeOK)
}
